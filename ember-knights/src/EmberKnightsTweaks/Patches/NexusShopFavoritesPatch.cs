using System;
using HarmonyLib;
using Il2CppSystem.Collections.Generic;

namespace EmberKnightsTweaks.Patches;

// The pre-run Nexus shop is stocked by GenerateNexusShopItems_AUTH, which only the
// host runs; the result syncs to clients through NexusShopData. The first stock
// (FromReroll = false) and every reroll (NumItems = items still on display) both
// come through here, so a postfix that swaps in favorites covers everything.
// Item net ids are kept, and the reroll caller restores slot indices afterwards.
[HarmonyPatch(typeof(GameCode.GameUtils), nameof(GameCode.GameUtils.GenerateNexusShopItems_AUTH))]
internal static class NexusShopFavoritesPatch
{
    private const eRelicPoolType NexusPool = eRelicPoolType.NexusShop;
    private const eAreaName NexusArea = eAreaName.Nexus;

    private static int cursor;

    private static void Postfix(GameCode.XWorld World, GameCode.SavedPlayerSlot SaveSlot, int NumItems,
        List<GameCode.NexusShopItem_t> OutItemList, bool FromReroll)
    {
        try
        {
            if (!FromReroll) cursor = 0;
            if (!Plugin.FavoritesEnabled.Value || World.IsDailyDungeon || World.IsBossRush) return;
            ApplyFavorites(World, SaveSlot, NumItems, OutItemList, FromReroll);
        }
        catch (Exception e)
        {
            Plugin.Logger.LogError($"NexusShopFavoritesPatch failed (reroll={FromReroll}, cursor={cursor}): {e}");
        }
    }

    private static void ApplyFavorites(GameCode.XWorld world, GameCode.SavedPlayerSlot slot, int numItems,
        List<GameCode.NexusShopItem_t> items, bool fromReroll)
    {
        var favorites = FavoriteQueue.Parse(Plugin.FavoriteRelics.Value);
        var first = Math.Max(0, items.Count - numItems); // only touch the items generated by this call
        var eligible = BuildEligibility(world, slot);
        var (picks, next) = FavoriteQueue.Take(favorites, cursor, items.Count - first, eligible);
        cursor = next;

        var originals = new System.Collections.Generic.List<int>();
        for (var i = 0; i < items.Count - first; i++) originals.Add(items[first + i].ItemDefId);
        var plan = FavoriteQueue.Place(originals, picks);
        for (var i = 0; i < plan.Count; i++)
            if (plan[i] != originals[i]) items[first + i] = WithRelic(items[first + i], plan[i]);

        Plugin.Logger.LogInfo($"Nexus shop {(fromReroll ? "reroll" : "stock")}: {Describe(items)} (cursor {cursor}/{favorites.Count})");
    }

    // Mirrors the generator's own relic filters so we never offer something the game wouldn't.
    private static Func<int, bool> BuildEligibility(GameCode.XWorld world, GameCode.SavedPlayerSlot slot)
    {
        var counts = new Dictionary<int, int>();
        GameCode.RelicUtils.GetRelicInstanceCounts(world, NexusArea, ref counts);
        return id =>
        {
            var def = XRelicDef.Get(id);
            return def != null && def.enabled && slot.IsItemUnlocked(def) && def.IsInPool(NexusPool, NexusArea)
                && GameCode.RelicUtils.PassesAllMaxOwnedChecks(def, counts, world.AllPlayers, null);
        };
    }

    private static GameCode.NexusShopItem_t WithRelic(GameCode.NexusShopItem_t item, int relicId)
    {
        item.ItemType = eItemType.Relic;
        item.ItemDefId = relicId;
        return item;
    }

    private static string Describe(List<GameCode.NexusShopItem_t> items)
    {
        var parts = new System.Collections.Generic.List<string>();
        foreach (var item in items) parts.Add($"{item.ItemType}:{item.ItemDefId}");
        return string.Join(", ", parts);
    }
}
